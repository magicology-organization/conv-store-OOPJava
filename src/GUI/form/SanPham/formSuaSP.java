    private void btnSuaActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_btnSuaActionPerformed
        // TODO add your handling code here:
        try {
            // Kiểm tra các trường không để trống
            if (txtTenSP.getText().isEmpty() || txtGiaNhap.getText().isEmpty() ||
                    txtGiaBan.getText().isEmpty() || txtSoLuong.getText().isEmpty()) {
                JOptionPane.showMessageDialog(this, "Vui lòng nhập đầy đủ thông tin sản phẩm.");
                return;
            }

            // Lấy thông tin từ form
            String tenSP = txtTenSP.getText();
            String moTa = txtMoTa.getText();
            String giaNhapStr = txtGiaNhap.getText();
            String giaBanStr = txtGiaBan.getText();
            String soLuongStr = txtSoLuong.getText();
            Date hsd = DateHSD.getDate(); // Lấy hạn sử dụng
            String danhMuc = (String) cboDanhMuc.getSelectedItem();
            String donViTinh = (String) cboDVT.getSelectedItem();
            String xuatXu = (String) cboXuatXu.getSelectedItem();

            // --- Bắt đầu kiểm tra dữ liệu nhập ---
            if (tenSP.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Vui lòng nhập tên sản phẩm!");
                return;
            }

            if (giaNhapStr.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Vui lòng nhập giá nhập của sản phẩm!");
                return;
            }
            if (!giaNhapStr.matches("^\\d+(\\.\\d+)?$")) {
                JOptionPane.showMessageDialog(this, "Giá nhập chỉ được nhập số và không chứa chữ hoặc ký tự đặc biệt!");
                return;
            }

            if (giaBanStr.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Vui lòng nhập giá bán của sản phẩm!");
                return;
            }
            if (!giaBanStr.matches("^\\d+(\\.\\d+)?$")) {
                JOptionPane.showMessageDialog(this, "Giá bán chỉ được nhập số và không chứa chữ hoặc ký tự đặc biệt!");
                return;
            }

            double giaNhap = Double.parseDouble(giaNhapStr);
            double giaBan = Double.parseDouble(giaBanStr);

            if (giaNhap < 0 || giaBan < 0) {
                JOptionPane.showMessageDialog(this, "Giá nhập và giá bán phải lớn hơn hoặc bằng 0!");
                return;
            }
            if (giaNhap > giaBan) {
                JOptionPane.showMessageDialog(this, "Giá nhập phải thấp hơn giá bán!");
                return;
            }

            if (soLuongStr.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Vui lòng nhập số lượng của sản phẩm!");
                return;
            }
            if (!soLuongStr.matches("^\\d+$")) {
                JOptionPane.showMessageDialog(this,
                        "Số lượng phải là số nguyên không âm và không được chứa chữ hoặc dấu thập phân!");
                return;
            }

            int soLuong = Integer.parseInt(soLuongStr);

            if (soLuong < 0) {
                JOptionPane.showMessageDialog(this, "Số lượng phải lớn hơn hoặc bằng 0!");
                return;
            }

            if (hsd == null) {
                JOptionPane.showMessageDialog(this, "Vui lòng chọn hạn sử dụng!");
                return;
            }
            Date today = new Date();
            if (!hsd.after(today)) {
                JOptionPane.showMessageDialog(this, "Hạn sử dụng phải là ngày sau hôm nay!");
                return;
            }
            // --- Kết thúc kiểm tra dữ liệu nhập ---

            if (danhMuc == null || donViTinh == null || xuatXu == null) {
                JOptionPane.showMessageDialog(this, "Vui lòng chọn đầy đủ danh mục, đơn vị tính và xuất xứ!");
                return;
            }

            String maDanhMuc = new DanhMucDAO().findAll().stream()
                    .filter(dm -> dm.getTenDM() != null && dm.getTenDM().trim().equalsIgnoreCase(danhMuc.trim()))
                    .map(DanhMuc::getMaDM)
                    .findFirst().orElse(null);

            String maDVT = new DonViTinhDAO().findAll().stream()
                    .filter(dvt -> dvt.getTenDVT() != null && dvt.getTenDVT().trim().equalsIgnoreCase(donViTinh.trim()))
                    .map(DonViTinh::getMaDVT)
                    .findFirst().orElse(null);

            String maXuatXu = new XuatXuDAO().findAll().stream()
                    .filter(xx -> xx.getTenXX() != null && xx.getTenXX().trim().equalsIgnoreCase(xuatXu.trim()))
                    .map(XuatXu::getMaXX)
                    .findFirst().orElse(null);

            // Tạo đối tượng SanPham để cập nhật
            SanPham sanPham = new SanPham(
                    txtMaSP.getText(), // Mã sản phẩm
                    tenSP, // Tên sản phẩm
                    imageData, // Ảnh (byte[])
                    moTa, // Mô tả sản phẩm
                    new DanhMuc(maDanhMuc, danhMuc),
                    new DonViTinh(maDVT, donViTinh),
                    new XuatXu(maXuatXu, xuatXu),
                    soLuong, // Số lượng
                    new java.math.BigDecimal(giaNhap),
                    new java.math.BigDecimal(giaBan),
                    hsd.toInstant().atZone(java.time.ZoneId.systemDefault()).toLocalDateTime());

            // Cập nhật thông tin sản phẩm vào cơ sở dữ liệu
            if (new SanPhamDAO().update(sanPham)) {
                JOptionPane.showMessageDialog(this, "Sửa sản phẩm thành công!");
                dispose(); // Đóng form sau khi sửa thành công
            } else {
                JOptionPane.showMessageDialog(this, "Có lỗi xảy ra khi sửa sản phẩm.");
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập giá trị hợp lệ cho giá nhập, giá bán và số lượng.");
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Có lỗi xảy ra khi sửa sản phẩm. Vui lòng kiểm tra lại dữ liệu.");
        }
    }// GEN-LAST:event_btnSuaActionPerformed

    private void btnThemAnhActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_btnThemAnhActionPerformed
        // TODO add your handling code here:
        JFileChooser fileChooser = new JFileChooser();
        fileChooser.setDialogTitle("Chọn ảnh sản phẩm");
        fileChooser.setFileFilter(new FileNameExtensionFilter("Ảnh (JPG, PNG, JPEG)", "jpg", "jpeg", "png"));

        int result = fileChooser.showOpenDialog(this);
        if (result == JFileChooser.APPROVE_OPTION) {
            File selectedFile = fileChooser.getSelectedFile();

            try {
                // Đọc ảnh gốc
                BufferedImage originalImage = ImageIO.read(selectedFile);
                if (originalImage == null) {
                    JOptionPane.showMessageDialog(this, "Không thể đọc định dạng ảnh này!");
                    return;
                }

                // Kích thước hiển thị cố định
                int targetWidth = 250;
                int targetHeight = 250;

                // Tính tỷ lệ để không méo ảnh
                double aspectRatio = (double) originalImage.getWidth() / originalImage.getHeight();
                int newWidth = targetWidth;
                int newHeight = (int) (targetWidth / aspectRatio);

                if (newHeight > targetHeight) {
                    newHeight = targetHeight;
                    newWidth = (int) (targetHeight * aspectRatio);
                }

                // Scale ảnh về kích thước phù hợp
                Image scaledImage = originalImage.getScaledInstance(newWidth, newHeight, Image.SCALE_SMOOTH);

                // Tạo ảnh đích có nền trong suốt (TYPE_INT_ARGB)
                BufferedImage finalImage = new BufferedImage(targetWidth, targetHeight, BufferedImage.TYPE_INT_ARGB);
                Graphics2D g2d = finalImage.createGraphics();

                // Không dùng Color.WHITE, chỉ vẽ ảnh vào giữa khung
                int x = (targetWidth - newWidth) / 2;
                int y = (targetHeight - newHeight) / 2;
                g2d.drawImage(scaledImage, x, y, null);
                g2d.dispose();

                // Gán lên JLabel
                lblAnh.setIcon(new ImageIcon(finalImage));

                // Chuyển ảnh sang mảng byte để lưu DB
                ByteArrayOutputStream baos = new ByteArrayOutputStream();
                ImageIO.write(finalImage, "png", baos);
                baos.flush();
                imageData = baos.toByteArray();
                baos.close();

            } catch (IOException e) {
                JOptionPane.showMessageDialog(this, "Lỗi khi đọc ảnh: " + e.getMessage());
            }
        }
    }// GEN-LAST:event_btnThemAnhActionPerformed

