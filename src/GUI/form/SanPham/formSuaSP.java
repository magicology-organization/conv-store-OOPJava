    private void loadComboBoxData() {
        List<DanhMuc> danhMucList = new DanhMucDAO().findAll();
        for (DanhMuc dm : danhMucList) {
            cboDanhMuc.addItem(dm.getTenDM().trim());
        }

        List<DonViTinh> dvtList = new DonViTinhDAO().findAll();
        for (DonViTinh dvt : dvtList) {
            cboDVT.addItem(dvt.getTenDVT().trim());
        }

        List<XuatXu> xxList = new XuatXuDAO().findAll();
        for (XuatXu xx : xxList) {
            cboXuatXu.addItem(xx.getTenXX().trim());
        }
    }

    public void setThongTinSP(Entity.SanPham.SanPham sp) {
        if (sp != null) {
            txtMaSP.setText(sp.getMaSP());
            txtTenSP.setText(sp.getTenSP());
            txtGiaNhap.setText(String.valueOf(sp.getGiaNhap()));
            txtGiaBan.setText(String.valueOf(sp.getDonGia()));
            txtSoLuong.setText(String.valueOf(sp.getSoLuong()));
            txtMoTa.setText(sp.getMoTaSP());
            DateHSD.setDate(
                    sp.getHsd() != null ? Date.from(sp.getHsd().atZone(ZoneId.systemDefault()).toInstant()) : null);

            cboDanhMuc.setSelectedItem(sp.getDanhMuc().getTenDM());
            cboDVT.setSelectedItem(sp.getDonViTinh().getTenDVT());
            cboXuatXu.setSelectedItem(sp.getXuatXu().getTenXX());

            lblAnh.setIcon(sp.getAnhSP() != null ? new ImageIcon(sp.getAnhSP()) : new FlatSVGIcon("./icon/image.svg"));
        }
    }

