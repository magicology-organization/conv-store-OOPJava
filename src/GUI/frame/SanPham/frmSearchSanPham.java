    private void configureTable() {
        // Ngăn không cho phép người dùng chỉnh sửa bảng
        table.setDefaultEditor(Object.class, null);

        // Căn giữa cho tất cả các cell trong bảng
        DefaultTableCellRenderer centerRenderer = new DefaultTableCellRenderer();
        centerRenderer.setHorizontalAlignment(JLabel.CENTER);

        // Căn giữa cho từng cột
        for (int i = 0; i < table.getColumnCount(); i++) {
            table.getColumnModel().getColumn(i).setCellRenderer(centerRenderer);
        }

        // Ngăn không cho phép chọn nhiều dòng
        table.setSelectionMode(javax.swing.ListSelectionModel.SINGLE_SELECTION);
    }

    private void loadDataTable() {
        DefaultTableModel model = (DefaultTableModel) table.getModel();
        model.setRowCount(0);

        SanPhamDAO dao = new SanPhamDAO();
        List<Object[]> list = dao.findAllWithDetails();
        int stt = 1;
        for (Object[] row : list) {
            String giaNhap = currencyFormat.format(row[6]); // giá nhập
            String giaBan = currencyFormat.format(row[7]); // đơn giá
            java.sql.Timestamp ts = (java.sql.Timestamp) row[9];
            String hsd = dateFormat.format(ts);

            model.addRow(new Object[] {
                    stt++, // STT
                    row[0], // Mã sản phẩm
                    row[1], // Tên sản phẩm
                    row[2], // Mô tả
                    hsd, // Hạn sử dụng
                    row[3], // Danh mục
                    row[4], // Xuất xứ
                    row[5], // Đơn vị tính
                    giaNhap, // Giá nhập
                    giaBan, // Giá bán
                    row[8], // Tồn kho
            });
        }
    }

    private void loadComboBoxData() {
        cboDanhMuc.removeAllItems();
        cboXuatXu.removeAllItems();
        cboDanhMuc.addItem("Tất cả");
        cboXuatXu.addItem("Tất cả");
        List<DanhMuc> danhMucList = new DanhMucDAO().findAll();
        for (DanhMuc dm : danhMucList) {
            cboDanhMuc.addItem(dm.getTenDM().trim());
        }

        List<XuatXu> xxList = new XuatXuDAO().findAll();
        for (XuatXu xx : xxList) {
            cboXuatXu.addItem(xx.getTenXX().trim());
        }
    }

