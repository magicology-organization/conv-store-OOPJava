    private void btnTimActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_btnTimActionPerformed
        // TODO add your handling code here:
        String maSP = txtMaSP.getText().trim();
        String tenSP = txtTenSP.getText().trim();
        String danhMuc = (String) cboDanhMuc.getSelectedItem();
        String xuatXu = (String) cboXuatXu.getSelectedItem();

        // Gọi DAO để tìm kiếm
        SanPhamDAO dao = new SanPhamDAO();
        List<Object[]> list = dao.search(maSP, tenSP, danhMuc, xuatXu);

        // Lấy model của bảng và xóa dữ liệu cũ
        DefaultTableModel model = (DefaultTableModel) table.getModel();
        model.setRowCount(0);

        // Thêm dữ liệu mới vào bảng
        int stt = 1;
        DecimalFormat currencyFormat = new DecimalFormat("#,### VND");
        for (Object[] row : list) {
            String giaNhap = currencyFormat.format(row[6]); // Giá nhập
            String giaBan = currencyFormat.format(row[7]); // Giá bán
            model.addRow(new Object[] {
                    stt++, // STT
                    row[0], // Mã SP
                    row[1], // Tên SP
                    row[2], // Mô tả
                    row[3], // Danh mục
                    row[4], // Xuất xứ
                    row[5], // Đơn vị tính
                    giaNhap, // Giá nhập
                    giaBan, // Giá bán
                    row[8] // Tồn kho
            });
        }

        // Hiển thị thông báo nếu không có kết quả
        if (model.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this,
                    "Không tìm thấy sản phẩm phù hợp!",
                    "Thông báo",
                    JOptionPane.INFORMATION_MESSAGE);
        }
    }// GEN-LAST:event_btnTimActionPerformed

    private void btnChiTietActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_btnChiTietActionPerformed
        // TODO add your handling code here:
        int row = table.getSelectedRow();
        if (row < 0) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Vui lòng chọn một sản phẩm để xem chi tiết!",
                    "Thông báo", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Lấy mã sản phẩm từ cột của bảng
        String maSP = table.getValueAt(row, 1).toString();

        // Lấy dữ liệu từ DAO
        DAO.SanPham.SanPhamDAO dao = new DAO.SanPham.SanPhamDAO();
        Entity.SanPham.SanPham sp = dao.findById(maSP).orElse(null);

        if (sp == null) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Không tìm thấy thông tin sản phẩm!",
                    "Lỗi", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Mở form chi tiết
        javax.swing.JFrame parent = (javax.swing.JFrame) javax.swing.SwingUtilities.getWindowAncestor(this);
        GUI.form.SanPham.formThongTinSP dialog = new GUI.form.SanPham.formThongTinSP(parent, true, sp);

        dialog.setLocationRelativeTo(this);

        dialog.setVisible(true);
    }// GEN-LAST:event_btnChiTietActionPerformed

